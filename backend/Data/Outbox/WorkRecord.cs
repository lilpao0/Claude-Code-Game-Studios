namespace CurioDistrict.Data.Outbox;

/// <summary>
/// The outbox/event work record that travels from the API host to the Worker
/// (story 008, FND-009, AC4's mechanism, recorded at implementation time
/// per the story's instruction).
///
/// Because the Worker is a separate process from the API, the correlation
/// id cannot ride the HTTP header alone: it is a field ON this record, so
/// it travels with the work the record describes. When EP-ECONOMY lands
/// the district tick and EP-AUTOMATION lands offline resolution, their
/// event producers persist rows of this shape; the Worker's log scope
/// helper (<c>WorkItemLogging.OpenWorkItemScope</c>) then re-attaches the
/// id on the Worker's side.
///
/// This record lives in Data, not Domain: the outbox is a persistence
/// seam (ADR-0004) and the id it carries is generated by the host, never
/// by Domain — story 007's purity scan keeps the generation out of
/// Domain's tree by construction.
/// </summary>
public sealed record WorkRecord(
    string WorkItemId,
    string WorkType,
    string CorrelationId,
    DateTimeOffset CreatedUtc);
